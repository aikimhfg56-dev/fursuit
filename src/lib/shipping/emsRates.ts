/** Looks up the EMS rate in JPY for a given zone and weight (kg), capping at the 30kg bracket. */
export function getEmsRateJpy(zone: EmsZone, weightKg: number): number {
  const grams = Math.max(0, weightKg) * 1000;
  const brackets = EMS_RATES_JPY[zone];
  const bracket = brackets.find(([maxGrams]) => grams <= maxGrams);
  return (bracket ?? brackets[brackets.length - 1])[1];
}
